import vm from 'node:vm';
import fs from 'node:fs/promises';
import path from 'node:path';
const root=path.resolve(process.argv[2]??'.');
const code=await fs.readFile(path.join(root,'src/LiveCG.Core/Browser/player.js'),'utf8');
const listeners=new Map();let now=0;
const ctx=new Proxy({},{get:()=>()=>{}});
const elements={livecg:{getContext:()=>ctx},error:{style:{}}};
const data={width:16,height:16,fps:30,source:'original.png',regions:[],assets:[],plan:{enabled:true,introFrames:30,loopEndFrame:90,endFrame:120,exitFrames:30,exitFade:true},playback:{replayOnShow:true,exitAtLoopEnd:true}};
const scope={LIVECG_DATA:data,obsstudio:{pluginVersion:'test'},addEventListener:(name,fn)=>listeners.set(name,fn)};
const sandbox={window:scope,document:{getElementById:id=>elements[id]??null,createElement:()=>({getContext:()=>ctx})},performance:{now:()=>now},requestAnimationFrame:()=>{},console,Image:class{set src(v){this.onload();}}};
vm.runInNewContext(code,sandbox);await new Promise(r=>setImmediate(r));
let count=0,failed=0;const check=(ok,name)=>{count++;if(!ok)failed++;console.log((ok?'PASS ':'FAIL ')+name)};
const event=(name,detail)=>listeners.get(name)?.({detail});
event('obsSourceVisibleChanged',{visible:true});event('obsSourceActiveChanged',{active:false});now=700;
check(scope.LiveCG.status().time<.01,'OBS preview waits at entrance frame instead of consuming it');
event('obsSourceActiveChanged',{active:true});check(scope.LiveCG.status().time<.01,'preview to program restarts at first entrance frame');
now=1000;event('obsSourceActiveChanged',{active:true});check(Math.abs(scope.LiveCG.status().time-.3)<.001,'duplicate activation does not restart during program playback');
event('obsSourceVisibleChanged',{visible:false});event('obsSourceVisibleChanged',{visible:true});check(Math.abs(scope.LiveCG.status().time-.3)<.001,'preview visibility change cannot restart a program-active source');
event('obsSourceActiveChanged',{active:false});now=2000;event('obsSourceActiveChanged',{active:true});check(scope.LiveCG.status().time<.01,'each return from preview to program replays entrance');
console.log(`RESULT ${count-failed}/${count} passed`);process.exitCode=failed?1:0;
